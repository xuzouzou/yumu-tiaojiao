private func ing(_ id: String, _ name: String, _ en: String, _ group: String) -> IngredientInfo {
    IngredientInfo(id: id, name: name, nameEN: en, group: group)
}

private func ri(_ id: String, _ amount: Double, _ unit: String = "ml", _ note: String = "") -> RecipeIngredient {
    RecipeIngredient(ingredientID: id, amount: amount, unit: unit, note: note)
}

